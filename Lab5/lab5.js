console.log("=== Лабораторна робота №5: Цикли ===");

// --------------------
// Завдання 1 (for): парні числа 1..20
console.log("----- Завдання 1: парні числа 1..20 -----");
for (let i = 1; i <= 20; i++) {
  if (i % 2 === 0) console.log(i);
}

// --------------------
// Завдання 2 (while): вивести числа від n до 1
console.log("----- Завдання 2: числа від n до 1 -----");

let nInput = prompt("Введіть число n (для завдання 2):");
if (nInput === null) {
  console.log("Завдання 2 скасовано (Cancel).");
} else {
  let n = parseInt(nInput, 10);

  if (isNaN(n)) {
    console.log("Помилка: введено не число. Завдання 2 пропущено.");
  } else {
    while (n >= 1) {
      console.log(n);
      n--;
    }
  }
}

